def cmd_pair(a):
    cat = catalog()
    pairs = load("pairings.json")["pairings"]
    if a.id:
        pairs = [p for p in pairs if p["id"] == a.id] or sys.exit(f"No pairing '{a.id}'.")
    scored = []
    for p in pairs:
        s = sum(1 for m in (a.mood or []) if m in p["moods"])
        if a.mood and not s:
            continue
        if a.arabic_first and "Arabic-first" not in p["name"] and "Urdu" not in p["name"]:
            continue
        if a.query and a.query.lower() not in (p["use"] + p["name"] + p["why"]).lower():
            continue
        scored.append((s, p))
    scored.sort(key=lambda t: -t[0])
    for _, p in scored[: a.limit]:
        name = lambda k: cat[p[k]]["family"] if p.get(k) in cat else (p.get(k) or "-")  # noqa: E731
        print(f"{p['id']:<20} {p['name']}  ({', '.join(p['moods'])})")
