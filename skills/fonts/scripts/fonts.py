# ----------------------------------------------------------------------------- helpers
def http_json(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
        return json.load(r)


def http_bytes(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


def load(name):
    return json.loads((DATA / name).read_text())


def catalog():
    p = DATA / "catalog.json"
    if not p.exists():
        sys.exit("catalog.json missing: run `fonts.py refresh` first.")
    return {f["id"]: f for f in json.loads(p.read_text())["fonts"]}


def get_font(cat, fid):
    if fid in cat:
        return cat[fid]
    # Allow family names ("IBM Plex Sans") as well as ids.
    norm = re.sub(r"[^a-z0-9]+", "-", fid.lower()).strip("-")
    if norm in cat:
        return cat[norm]
    close = [k for k in cat if norm in k or k in norm]
    msg = f"'{fid}' is not in the curated catalogue."
    if close:
        msg += " Did you mean: " + ", ".join(close[:6]) + "?"
    msg += " Any Fontsource id works with `fonts.py lookup <id>` (fetches live metadata)."
    sys.exit(msg)


def lookup_remote(fid):
    """Fontsource metadata for any font, curated or not."""
    try:
        d = http_json(f"{API}/fonts/{fid}")
    except Exception as e:  # noqa: BLE001
        sys.exit(f"Fontsource has no font '{fid}' ({e}). Search https://fontsource.org/?query={fid}")
    f = {k: d.get(k) for k in ("id", "family", "subsets", "weights", "styles", "defSubset", "variable",
                               "category", "license", "type", "version")}
    f.update(roles=[], moods=[], note="(not curated: fetched live from Fontsource)", repo=None)
    return f


def family_css(f, source="google"):
    """Family name as it appears in CSS. Fontsource variable packages register '<Family> Variable'."""
    if source == "fontsource" and f.get("variable"):
        return f"{f['family']} Variable"
    return f["family"]


def fallback_kind(f):
    c = f.get("category")
    return "courier" if c == "monospace" else "times" if c == "serif" else "arial"


def arabic_primary(f):
    """True for fonts whose main job is Arabic-script text (Latin-measured fallbacks make no sense for them)."""
    roles = f.get("roles") or []
    return bool(roles) and (roles[0] in ("arabic", "urdu") or "urdu" in roles or "latin" not in (f.get("subsets") or ["latin"]))


def has_fallback(f):
    return bool(f.get("metrics", {}).get("xavg")) and not arabic_primary(f)


def stack_for(f, source="google", with_fallback=True):
    parts = [f"'{family_css(f, source)}'"]
    if with_fallback and has_fallback(f):
        parts.append(f"'{f['family']} Fallback'")
    roles = f.get("roles") or []
    if "urdu" in roles:
        parts.append(SYSTEM_STACKS["urdu-nastaliq"])
    elif "arabic" in roles:
        parts.append(SYSTEM_STACKS["arabic"])
    else:
        parts.append(SYSTEM_STACKS[CATEGORY_STACK.get(f.get("category"), "system-ui")])
    out = []  # de-duplicate while keeping order
    for x in ", ".join(parts).split(", "):
        if x not in out:
            out.append(x)
    return ", ".join(out)


def scripts_of(f):
    s = set(f.get("subsets") or [])
    out = []
    if "latin" in s or not s:
        out.append("latin")
    for k in ("latin-ext", "cyrillic", "greek", "vietnamese", "arabic", "hebrew", "devanagari"):
        if k in s:
            out.append(k)
    if f.get("urdu_ok"):
        out.append("urdu-letters")
    if "urdu" in (f.get("roles") or []):
        out.append("urdu")
    if "cjk" in (f.get("roles") or []):
        out.append("cjk")
    return out


def pick_weights(f, wanted):
    avail = f.get("weights") or [400]
    if f.get("variable") and wanted == "all":
        return avail
    if wanted in (None, "", "auto"):
        base = [w for w in (400, 500, 600, 700) if w in avail]
        return base or [avail[len(avail) // 2]]
    if wanted == "all":
        return avail
    req = [int(w) for w in str(wanted).split(",")]
    out = []
    for w in req:
        out.append(w if w in avail else min(avail, key=lambda a: abs(a - w)))
    return sorted(set(out))


def native_name(f, w, style="normal"):
    """File name used for native (iOS/Android/Flutter) TTFs, e.g. IBMPlexSansArabic-SemiBold.ttf."""
    wn = WEIGHT_NAMES.get(w, str(w))
    if style == "italic":
        wn = "Italic" if wn == "Regular" else wn + "Italic"
    return f"{ident(f['family'], 'pascal')}-{wn}.ttf"


def wght_range(f):
    ax = (f.get("axes") or {}).get("wght")
    if ax:
        return int(float(ax["min"])), int(float(ax["max"]))
    w = f.get("weights") or [400]
    return min(w), max(w)


def ident(family, style="pascal"):
    words = re.findall(r"[A-Za-z0-9]+", family)
    if style == "next":
        return "_".join(words)
    if style == "pascal":
        return "".join(words)
    if style == "camel":  # Flutter google_fonts method names
        out = []
        for i, w in enumerate(words):
            if w.isupper() and len(w) > 1:
                w = w.lower() if i == 0 else w.capitalize()
            elif i == 0:
                w = w[0].lower() + w[1:]
            out.append(w)
        return "".join(out)
    if style == "var":
        return ident(family, "camel")
    raise ValueError(style)


# ----------------------------------------------------------------------------- metrics
def measure(font_bytes):
    from fontTools.ttLib import TTFont
    tt = TTFont(io.BytesIO(font_bytes), lazy=True)
    upm = tt["head"].unitsPerEm
    hhea, os2 = tt["hhea"], tt["OS/2"]
    use_typo = bool(getattr(os2, "fsSelection", 0) & (1 << 7))
    if use_typo:
        asc, desc, gap = os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap
    else:
        asc, desc, gap = hhea.ascent, hhea.descent, hhea.lineGap
    cmap = tt.getBestCmap() or {}
    hmtx = tt["hmtx"]
    xavg = None
    if all(ord(c) in cmap for c in LETTER_FREQ):
        tot = sum(LETTER_FREQ.values())
        xavg = round(sum(hmtx[cmap[ord(c)]][0] * w for c, w in LETTER_FREQ.items()) / tot, 2)
    return {"upm": upm, "asc": asc, "desc": desc, "gap": gap, "xavg": xavg,
            "cap": getattr(os2, "sCapHeight", 0) or None, "xh": getattr(os2, "sxHeight", 0) or None}


def fallback_css(f, kind=None, name=None):
    m = f.get("metrics") or {}
    fb = SYSTEM_FALLBACKS[kind or fallback_kind(f)]
    name = name or f"{f['family']} Fallback"
    local = ", ".join(f"local('{n}')" for n in fb["local"])
    if not m.get("xavg") or arabic_primary(f):
        return (f"/* {f['family']}: Arabic-script font, so no Latin-measured fallback; the platform Arabic "
                f"stack in its font-family covers the swap. */\n")
    size_adjust = (m["xavg"] / m["upm"]) / (fb["xavg"] / fb["upm"])
    pct = lambda v: f"{v * 100:.4f}%"  # noqa: E731
    body = (f"  size-adjust: {pct(size_adjust)};\n"
            f"  ascent-override: {pct(m['asc'] / (m['upm'] * size_adjust))};\n"
            f"  descent-override: {pct(abs(m['desc']) / (m['upm'] * size_adjust))};\n"
            f"  line-gap-override: {pct(m['gap'] / (m['upm'] * size_adjust))};\n}}\n")
    # Two faces so bold text uses the real bold system font instead of faux-bolding the regular one
    # (faux bold is wider, which changes wrapping during the swap). Bold widths differ a little from
    # regular; the size-adjust is measured on regular, which is what most text is set in.
    bold = ", ".join(f"local('{n}')" for n in fb["bold"])
    return (f"@font-face {{\n  font-family: '{name}';\n  src: {local};\n  font-weight: 100 549;\n{body}"
            f"@font-face {{\n  font-family: '{name}';\n  src: {bold};\n  font-weight: 550 1000;\n{body}")


