def cmd_refresh(a):
    cur = load("curated.json")
    entries, overrides = cur["fonts"], cur.get("overrides", {})
    old = {}
    if (DATA / "catalog.json").exists():
        old = {f["id"]: f for f in json.loads((DATA / "catalog.json").read_text())["fonts"]}
    print(f"Fetching Fontsource index ({len(entries)} curated fonts)...", file=sys.stderr)
    index = {f["id"]: f for f in http_json(f"{API}/fonts")}
    out, missing = [], []

    def build(e):
        fid, roles, moods, note, repo = e
        if fid not in index:
            return None
        f = {k: index[fid].get(k) for k in ("id", "family", "subsets", "weights", "styles", "defSubset",
                                           "variable", "category", "license", "type", "lastModified")}
        f.update(roles=roles, moods=moods, note=note, repo=repo)
        f.update(overrides.get(fid, {}))
        if f["variable"]:
            try:
                f["axes"] = http_json(f"{API}/variable/{fid}").get("axes")
            except Exception:  # noqa: BLE001
                f["axes"] = old.get(fid, {}).get("axes")
        if "arabic" in (f.get("subsets") or []):
            if "urdu_ok" in old.get(fid, {}) and not a.remeasure:
                f["urdu_ok"] = old[fid]["urdu_ok"]
            else:
                try:
                    from fontTools.ttLib import TTFont
                    cm = TTFont(io.BytesIO(http_bytes(f"{CDN}/{fid}@latest/arabic-{400 if 400 in f['weights'] else f['weights'][0]}-normal.ttf"))).getBestCmap()
                    f["urdu_ok"] = all(u in cm for u in URDU_LETTERS)
                except Exception as ex:  # noqa: BLE001
                    print(f"  urdu check failed for {fid}: {ex}", file=sys.stderr)
        if not a.no_metrics:
            if old.get(fid, {}).get("metrics") and not a.remeasure:
                f["metrics"] = old[fid]["metrics"]
            else:
                w = 400 if 400 in f["weights"] else f["weights"][0]
                try:
                    f["metrics"] = measure(http_bytes(f"{CDN}/{fid}@latest/{f['defSubset']}-{w}-normal.ttf"))
                except Exception as ex:  # noqa: BLE001
                    print(f"  metrics failed for {fid}: {ex}", file=sys.stderr)
        return f

    with cf.ThreadPoolExecutor(12) as ex:
        for e, f in zip(entries, ex.map(build, entries)):
            (out.append(f) if f else missing.append(e[0]))
    (DATA / "catalog.json").write_text(json.dumps({"source": "fontsource + curated.json", "fonts": out},
                                                  ensure_ascii=False, indent=1))
    print(f"Wrote catalog.json: {len(out)} fonts.", file=sys.stderr)
    if missing:
        print("Not on Fontsource (left out): " + ", ".join(missing), file=sys.stderr)
    pairs = load("pairings.json")["pairings"]
    ids = {f["id"] for f in out}
    for p in pairs:
        for k in ("heading", "body", "mono", "arabic", "arabic_display", "latin_partner"):
            if p.get(k) and p[k] not in ids:
                print(f"  pairing {p['id']}: {k}={p[k]} is not in the catalogue", file=sys.stderr)


def fmt_font(f, verbose=False):
    var = "variable" if f.get("variable") else "static"
    wr = f"{wght_range(f)[0]}-{wght_range(f)[1]}"
    ital = " +italic" if "italic" in (f.get("styles") or []) else ""
    host = "Google+Fontsource" if f.get("type") == "google" else "Fontsource only (not Google Fonts)"
    line = (f"{f['id']:<28} {f['family']}  [{f.get('category')}, {var} {wr}{ital}]\n"
            f"    roles: {', '.join(f.get('roles') or [])} | moods: {', '.join(f.get('moods') or [])}\n"
            f"    scripts: {', '.join(scripts_of(f))} | {host} | {f.get('license')}\n"
            f"    {f.get('note')}")
    if verbose:
        axes = f.get("axes") or {}
        if axes:
            line += "\n    axes: " + ", ".join(f"{k} {v['min']}-{v['max']} (default {v['default']})"
                                             for k, v in axes.items())
        line += f"\n    weights: {f.get('weights')}  styles: {f.get('styles')}"
        if f.get("repo"):
            line += f"\n    source: https://github.com/{f['repo']}"
        line += f"\n    fontsource: https://fontsource.org/fonts/{f['id']}"
        if f.get("type") == "google":
            line += f"\n    google: https://fonts.google.com/specimen/{f['family'].replace(' ', '+')}"
        line += f"\n    css stack: font-family: {stack_for(f)};"
    return line


def cmd_find(a):
    cat = catalog()
    res = []
    for f in cat.values():
        if a.role and not all(r in f["roles"] for r in a.role):
            continue
        if a.script and not all(s in scripts_of(f) for s in a.script):
            continue
        if a.category and f.get("category") != a.category:
            continue
        if a.variable and not f.get("variable"):
            continue
        if a.google and f.get("type") != "google":
            continue
        if a.italic and "italic" not in (f.get("styles") or []):
            continue
        score = sum(2 for m in (a.mood or []) if m in f["moods"])
        if a.mood and score == 0:
            continue
        if a.query:
            q = a.query.lower()
            if q not in (f["family"] + " " + f["note"] + " " + " ".join(f["moods"])).lower():
                continue
        score += 0.5 if f.get("variable") else 0
        res.append((score, f))
    res.sort(key=lambda t: (-t[0], t[1]["family"]))
    if not res:
        print("No matches. Loosen filters, or try `fonts.py lookup <fontsource-id>` for uncurated fonts.")
    for _, f in res[: a.limit]:
        print(fmt_font(f) + "\n")


def cmd_show(a):
    cat = catalog()
    for fid in a.ids:
        f = cat.get(fid) or (get_font(cat, fid) if not a.remote else lookup_remote(fid))
        print(fmt_font(f, verbose=True) + "\n")


def cmd_lookup(a):
    f = lookup_remote(a.id)
    try:
        if f.get("variable"):
            f["axes"] = http_json(f"{API}/variable/{a.id}").get("axes")
    except Exception:  # noqa: BLE001
        pass
    print(fmt_font(f, verbose=True))


def resolve_pairing(p, cat):
    """Map a pairing to concrete Latin/Arabic roles. Arabic-first pairings name a latin_partner for Latin text."""
    lp = p.get("latin_partner")
    latin_ok = lambda i: bool(i) and "latin" in (cat.get(i, {}).get("subsets") or []) \
        and not arabic_primary(cat.get(i, {}))  # noqa: E731
