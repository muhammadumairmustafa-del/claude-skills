def cmd_download(a):
    cat = catalog()
    f = cat.get(a.id) or lookup_remote(a.id)
    meta = http_json(f"{API}/fonts/{f['id']}")
    ur = meta.get("unicodeRange") or {}
    subsets = a.subsets.split(",") if a.subsets else [s for s in ("latin", "latin-ext", "arabic") if s in f["subsets"]] or [f["defSubset"]]
    bad = [s for s in subsets if s not in f["subsets"]]
    if bad:
        sys.exit(f"{f['family']} has no subset {bad}. Available: {f['subsets']}")
    styles = ["normal"] + (["italic"] if a.italic and "italic" in f["styles"] else [])
    outdir = Path(a.out) / f["id"]
    outdir.mkdir(parents=True, exist_ok=True)
    if a.format == "ttf" and f.get("type") == "google":
        return download_native(f, outdir, styles, a)
    if a.format == "ttf":
        print(f"Note: {f['family']} is not on Google Fonts, so these TTFs are split per subset ({', '.join(subsets)}). "
              "For native apps download the full TTF from the source repo instead.", file=sys.stderr)
    use_var = f.get("variable") and a.format == "woff2" and not a.static
    jobs = []
    for sub in subsets:
        for style in styles:
            if use_var:
                jobs.append((sub, "wght", style, f"{CDN}/{f['id']}:vf@latest/{sub}-wght-{style}.woff2",
                             f"{f['id']}-{sub}-wght-{style}.woff2"))
            else:
                for w in pick_weights(f, a.weights):
                    jobs.append((sub, w, style, f"{CDN}/{f['id']}@latest/{sub}-{w}-{style}.{a.format}",
                                 f"{f['id']}-{sub}-{w}-{style}.{a.format}"))
    faces, total = [], 0

    def fetch(j):
        b = http_bytes(j[3])
        (outdir / j[4]).write_bytes(b)
        return len(b)

    with cf.ThreadPoolExecutor(8) as ex:
        for j, n in zip(jobs, ex.map(fetch, jobs)):
            total += n
            sub, w, style, _, fn = j
            wdecl = f"{wght_range(f)[0]} {wght_range(f)[1]}" if w == "wght" else w
            fmt = {"woff2": "woff2", "woff": "woff", "ttf": "truetype"}[a.format]
            faces.append(f"/* {sub} */\n@font-face {{\n  font-family: '{f['family']}';\n  font-style: {style};\n"
                         f"  font-weight: {wdecl};\n  font-display: {a.display};\n"
                         f"  src: url('{a.url_prefix.rstrip('/')}/{f['id']}/{fn}') format('{fmt}');\n"
                         + (f"  unicode-range: {ur[sub]};\n" if sub in ur else "") + "}\n")
    css = "\n".join(faces) + "\n" + fallback_css(f) if f.get("metrics") else "\n".join(faces)
    if a.format != "ttf":
        (outdir / "fonts.css").write_text(css)
    write_license(f, outdir)
    print(f"Downloaded {len(jobs)} files ({total / 1024:.0f} KB) to {outdir}")
    if a.format != "ttf":
        pref = "arabic" if arabic_primary(f) and "arabic" in subsets else subsets[0]
        first = next(j[4] for j in jobs if j[0] == pref)
        print(f"CSS: {outdir / 'fonts.css'}\nFamily stack: font-family: {stack_for(f)};")
        print(f'Preload the main file: <link rel="preload" href="{a.url_prefix.rstrip("/")}/{f["id"]}/{first}" as="font" type="font/woff2" crossorigin>')


def write_license(f, outdir):
    """Ship the real licence text (OFL requires it to travel with the fonts). google/fonts keeps one per family."""
    lic = (f.get("license") or "").upper()
    folder = "apache" if "APACHE" in lic else "ufl" if "UFL" in lic else "ofl"
    slug = re.sub(r"[^a-z0-9]", "", f["family"].lower())
    fname = "LICENSE.txt" if folder == "apache" else "OFL.txt" if folder == "ofl" else "UFL.txt"
    head = (f"{f['family']} ({f.get('license')})\nSource: "
            + (f"https://github.com/{f['repo']}" if f.get("repo") else f"https://fontsource.org/fonts/{f['id']}") + "\n\n")
    try:
        text = http_bytes(f"https://raw.githubusercontent.com/google/fonts/main/{folder}/{slug}/{fname}").decode()
    except Exception:  # noqa: BLE001
        text = ("Full licence text not found automatically. Copy OFL.txt / LICENSE from the source repo above "
                "(OFL-1.1 requires the licence to accompany the font files).\n")
    (outdir / "LICENSE.txt").write_text(head + text)


def download_native(f, outdir, styles, a):
    """Full (unsubsetted) static TTFs from Google Fonts: every script in one file, one file per weight.
    Google serves TrueType with no unicode-range to clients that are not modern browsers."""
    from urllib.parse import quote
    ws = pick_weights(f, a.weights)
    ital = "italic" in styles
    spec = ("ital,wght@" + ";".join([f"0,{w}" for w in ws] + ([f"1,{w}" for w in ws] if ital else []))) \
        if ital else "wght@" + ";".join(map(str, ws))
    css = urllib.request.urlopen(urllib.request.Request(
        f"https://fonts.googleapis.com/css2?family={quote(f['family'])}:{spec}", headers=UA), timeout=30).read().decode()
    faces = re.findall(r"font-style:\s*(\w+);\s*font-weight:\s*(\d+);\s*src:\s*url\((.*?)\)", css)
    total, ps = 0, []
    for style, w, url in faces:
        b = http_bytes(url)
        fn = native_name(f, int(w), style)
        (outdir / fn).write_bytes(b)
        total += len(b)
        try:
            from fontTools.ttLib import TTFont
            ps.append((fn, TTFont(io.BytesIO(b), lazy=True)["name"].getDebugName(6)))
        except Exception:  # noqa: BLE001
            ps.append((fn, "?"))
    write_license(f, outdir)
    print(f"Downloaded {len(faces)} full TTFs ({total / 1024:.0f} KB) to {outdir}")
    print("File -> PostScript name (iOS Font.custom / UIFont(name:) wants the PostScript name; "
          "Android res/font needs lowercase_underscore file names):")
    for fn, n in ps:
        print(f"  {fn:<44} {n}")


def cmd_fallback(a):
    cat = catalog()
    for fid in a.ids:
        if a.file:
            f = {"family": fid, "category": a.category or "sans-serif", "metrics": measure(Path(a.file).read_bytes())}
        else:
            f = cat.get(fid) or lookup_remote(fid)
            if not f.get("metrics"):
                w = 400 if 400 in f["weights"] else f["weights"][0]
                f["metrics"] = measure(http_bytes(f"{CDN}/{f['id']}@latest/{f['defSubset']}-{w}-normal.ttf"))
        print(fallback_css(f, a.against))
        print(f"/* use: font-family: '{f['family']}', '{f['family']} Fallback', "
              f"{SYSTEM_STACKS[CATEGORY_STACK.get(f.get('category'), 'system-ui')]}; */\n")


def collect_text(root):
    chars = set(chr(c) for c in range(0x20, 0x7F))
    n = 0
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in SKIP_DIRS and not d.startswith(".")]
        for fn in fns:
            if Path(fn).suffix.lower() in SCAN_EXT:
                try:
                    chars |= set(Path(dp, fn).read_text(errors="ignore"))
                    n += 1
                except OSError:
                    pass
    chars = {c for c in chars if c.isprintable() or c in "‌‍‎‏"}
    return "".join(sorted(chars)), n


